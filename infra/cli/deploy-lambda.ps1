<#
.SYNOPSIS
    Packages src/bedrock_rag/ and creates or updates the CapitalMarketsRAG Lambda function.

.DESCRIPTION
    1. Zips the Python files in src/bedrock_rag/ into dist/<FunctionName>.zip. Entries use
       forward slashes so they unpack correctly on Lambda's Linux runtime.
    2. Adds a one-line handler.py at the zip root that re-exports
       bedrock_rag.handler.lambda_handler. This lets the Lambda handler be
       "handler.lambda_handler" while the code stays a proper package (it uses relative imports).
    3. If the function exists, updates its code and then re-applies its configuration;
       otherwise creates it.

    boto3 is not bundled; the Lambda Python runtime already provides it.
    Requires AWS CLI v2 and credentials (e.g. $env:AWS_PROFILE = "admin").

.EXAMPLE
    $env:AWS_PROFILE = "admin"
    .\infra\cli\deploy-lambda.ps1

.EXAMPLE
    .\infra\cli\deploy-lambda.ps1 -PackageOnly    # build the zip without calling AWS
#>
[CmdletBinding()]
param(
    [string] $FunctionName   = "CapitalMarketsRAG",
    [string] $Region         = "us-east-1",
    [string] $ProjectName    = "bedrock-rag",
    [string] $RoleName       = "bedrock-rag-lambda-exec",
    [string] $BucketName,
    [string] $Runtime        = "python3.11",
    [string] $Handler        = "handler.lambda_handler",
    # Lambda's 3s default is too short for Bedrock model calls.
    [int]    $TimeoutSeconds = 60,
    [int]    $MemoryMB       = 512,
    [switch] $PackageOnly
)

$ErrorActionPreference = "Stop"
$env:AWS_PAGER = ""

function Invoke-Aws {
    # Runs the AWS CLI and throws on a non-zero exit code.
    $output = & aws @args --region $Region
    if ($LASTEXITCODE -ne 0) { throw "Command failed (exit $LASTEXITCODE): aws $($args -join ' ')" }
    return $output
}

function Test-AwsCommand {
    # Returns $true if the AWS CLI command succeeds (used for existence checks).
    $ErrorActionPreference = "Continue"
    & aws @args --region $Region 2>&1 | Out-Null
    return ($LASTEXITCODE -eq 0)
}

$repoRoot   = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
$srcDir     = Join-Path $repoRoot "src"
$packageDir = Join-Path $srcDir "bedrock_rag"
$distDir    = Join-Path $repoRoot "dist"
$zipPath    = Join-Path $distDir "$FunctionName.zip"

$shimSource = @'
# Generated by deploy-lambda.ps1. Exposes the package handler at the zip root so the
# Lambda handler setting can be "handler.lambda_handler".
from bedrock_rag.handler import lambda_handler  # noqa: F401
'@

# ------------------------------------------------------------------ Package
Write-Host "Packaging $packageDir -> $zipPath" -ForegroundColor Cyan

$files = @(Get-ChildItem -Path $packageDir -Filter "*.py" -Recurse -File)
if ($files.Count -eq 0) { throw "No .py files found in $packageDir" }

New-Item -ItemType Directory -Force -Path $distDir | Out-Null
if (Test-Path $zipPath) { Remove-Item $zipPath -Force }

# Use System.IO.Compression directly: Compress-Archive on Windows PowerShell 5.1 can write
# backslash paths, which Lambda doesn't treat as directories.
Add-Type -AssemblyName System.IO.Compression
Add-Type -AssemblyName System.IO.Compression.FileSystem

$zip = [System.IO.Compression.ZipFile]::Open($zipPath, [System.IO.Compression.ZipArchiveMode]::Create)
try {
    foreach ($file in $files) {
        # Path relative to src/, e.g. bedrock_rag/handler.py
        $entryName = $file.FullName.Substring($srcDir.Length + 1).Replace("\", "/")
        [System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile($zip, $file.FullName, $entryName) | Out-Null
        Write-Host "  + $entryName"
    }

    $writer = New-Object System.IO.StreamWriter($zip.CreateEntry("handler.py").Open())
    try { $writer.Write($shimSource) } finally { $writer.Dispose() }
    Write-Host "  + handler.py (entry-point shim)"
}
finally {
    $zip.Dispose()
}

if ($PackageOnly) {
    Write-Host "Package built; skipping deployment (-PackageOnly)." -ForegroundColor Green
    return
}

# ------------------------------------------------------------------ Deploy
$accountId   = Invoke-Aws sts get-caller-identity --query Account --output text
if (-not $BucketName) { $BucketName = "$ProjectName-docs-$accountId-$Region" }
$roleArn     = Invoke-Aws iam get-role --role-name $RoleName --query Role.Arn --output text
$environment = "Variables={BUCKET_NAME=$BucketName}"
$zipArg      = "fileb://$zipPath"

Write-Host "Function: $FunctionName  Region: $Region  Bucket: $BucketName  Role: $roleArn" -ForegroundColor Cyan

if (Test-AwsCommand lambda get-function --function-name $FunctionName) {
    Write-Host "Function exists; updating code..."
    Invoke-Aws lambda update-function-code `
        --function-name $FunctionName `
        --zip-file $zipArg | Out-Null
    Invoke-Aws lambda wait function-updated-v2 --function-name $FunctionName | Out-Null

    # Keep runtime/handler/role/env in sync with this script. Must wait for the code
    # update to finish first, or Lambda rejects this call with ResourceConflictException.
    Write-Host "Updating configuration..."
    Invoke-Aws lambda update-function-configuration `
        --function-name $FunctionName `
        --runtime $Runtime `
        --handler $Handler `
        --role $roleArn `
        --timeout $TimeoutSeconds `
        --memory-size $MemoryMB `
        --environment $environment | Out-Null
    Invoke-Aws lambda wait function-updated-v2 --function-name $FunctionName | Out-Null
}
else {
    Write-Host "Creating function..."
    Invoke-Aws lambda create-function `
        --function-name $FunctionName `
        --runtime $Runtime `
        --handler $Handler `
        --role $roleArn `
        --zip-file $zipArg `
        --timeout $TimeoutSeconds `
        --memory-size $MemoryMB `
        --environment $environment | Out-Null
    Invoke-Aws lambda wait function-active-v2 --function-name $FunctionName | Out-Null
}

$functionArn = Invoke-Aws lambda get-function-configuration `
    --function-name $FunctionName --query FunctionArn --output text

Write-Host ""
Write-Host "Done." -ForegroundColor Green
Write-Host "  function_arn = $functionArn"
